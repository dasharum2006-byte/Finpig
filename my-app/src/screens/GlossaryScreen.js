export default function GlossaryScreen({ navigation }) {
  const [expandedId, setExpandedId] = useState(null);

  const toggle = (id) => {
    setExpandedId((prev) => (prev === id ? null : id));
  };

  return (
    <SafeAreaView style={styles.container} edges={['bottom']}>
      <ScrollView contentContainerStyle={styles.scroll}>
        <TouchableOpacity onPress={() => navigation.goBack()}>
          <Text style={styles.backBtn}>← Назад</Text>
        </TouchableOpacity>

        <Text style={styles.title}>📖 Справочник</Text>
        <Text style={styles.subtitle}>
          Простые объяснения финансовых слов. Нажми на термин, чтобы раскрыть.
        </Text>

        {TERMS.map((term) => {
          const isOpen = expandedId === term.id;
          return (
            <TouchableOpacity
              key={term.id}
              style={[styles.card, isOpen && styles.cardOpen]}
              onPress={() => toggle(term.id)}
              activeOpacity={0.7}
            >
              <View style={styles.header}>
                <Text style={styles.emoji}>{term.emoji}</Text>
                <Text style={styles.termTitle}>{term.title}</Text>
                <Text style={styles.arrow}>{isOpen ? '▾' : '▸'}</Text>
              </View>
              {isOpen && (
                <Text style={styles.termText}>{term.text}</Text>
              )}
            </TouchableOpacity>
          );
        })}
      </ScrollView>
    </SafeAreaView>
  );
}

